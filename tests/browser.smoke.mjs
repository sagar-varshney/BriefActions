// Run after `pnpm build` and `pnpm exec playwright install chromium`.
import assert from 'node:assert/strict';
import {mkdtemp, mkdir, readFile, rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {chromium} from 'playwright';
import {createApp} from '../server/index.mjs';

const folder=await mkdtemp(path.join(tmpdir(),'flow-browser-'));
const screenshotDir=process.env.FLOW_SCREENSHOTS || path.join(folder,'screenshots');
await mkdir(screenshotDir,{recursive:true});
const server=createApp({historyPath:path.join(folder,'history.sqlite3')});
let browser;
try {
  await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(0,'127.0.0.1',resolve);});
  const base=`http://127.0.0.1:${server.address().port}`;
  browser=await chromium.launch({headless:true, ...(process.env.FLOW_CHROMIUM_PATH ? {executablePath:process.env.FLOW_CHROMIUM_PATH} : {})});
  const page=await browser.newPage({viewport:{width:1440,height:1000}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  const visible=async (text)=>assert.ok(await page.getByText(text,{exact:true}).isVisible());
  await page.goto(base);
  await page.getByRole('button',{name:'Analyze transcript'}).waitFor();
  await page.waitForFunction(()=>document.querySelector('#transcript').value.includes('Maya'));
  await page.screenshot({path:path.join(screenshotDir,'desktop-home.png'),fullPage:true});
  await page.getByLabel('Meeting transcript',{exact:true}).fill('Maya will review the risks tomorrow.\nMaya will review the risks tomorrow.\nJon will send the invoice.');
  await page.getByLabel('Meeting date',{exact:true}).fill('2026-09-15');
  await page.getByRole('button',{name:'Analyze transcript'}).click();
  await page.getByRole('checkbox',{name:'Keep task 1'}).waitFor();
  assert.equal(await page.getByRole('checkbox').count(),2);
  assert.equal(await page.getByRole('checkbox',{checked:true}).count(),0);
  assert.equal(await page.locator('.proposal-card').first().locator('blockquote').count(),2);
  await page.getByLabel('Owner 1',{exact:true}).fill('Ravi');
  await page.getByLabel('Task 1',{exact:true}).fill('Review launch risks');
  await page.getByRole('checkbox',{name:'Keep task 1'}).check();
  await page.screenshot({path:path.join(screenshotDir,'desktop-review.png'),fullPage:true});
  await page.getByLabel('Deadline 1').fill('bad-date');
  await page.getByRole('button',{name:'Confirm selected tasks'}).click();
  await page.getByRole('alert').waitFor();
  assert.ok((await page.getByRole('alert').textContent()).includes('YYYY-MM-DD'));
  assert.equal(await page.locator('.proposal-card').count(),2);
  await page.getByLabel('Deadline 1').fill('2026-09-30');
  await page.getByRole('button',{name:'Confirm selected tasks'}).click();
  await page.getByRole('heading',{name:'Your confirmed plan'}).waitFor();
  assert.equal(await page.locator('.confirmed-card').count(),1);
  await visible('Review launch risks');await visible('Ravi');await visible('2026-09-30');
  const csvDownload=page.waitForEvent('download');await page.getByRole('link',{name:'Export CSV'}).click();
  const csv=await readFile(await (await csvDownload).path(),'utf8');
  assert.ok(csv.includes('Review launch risks'));assert.ok(csv.includes('Ravi'));assert.ok(csv.includes('Maya will review the risks tomorrow.'));assert.ok(!csv.includes('Jon'));
  const historyDownload=page.waitForEvent('download');await page.getByRole('link',{name:'History JSON'}).click();
  const audit=JSON.parse(await readFile(await (await historyDownload).path(),'utf8'));
  assert.deepEqual(audit.map(e=>e.kind),['extraction','review','final']);
  assert.equal(audit[0].payload.proposals[0].owner,'Maya');
  assert.equal(audit[1].payload.decisions[0].corrections.owner.after,'Ravi');
  assert.equal(audit[1].payload.decisions[1].accept,false);
  await page.reload();await page.getByRole('heading',{name:'Your confirmed plan'}).waitFor();
  await page.getByRole('button',{name:'Run history'}).click();await page.getByRole('button',{name:'Open run'}).waitFor();
  assert.equal(await page.locator('.history-card').count(),1);
  await page.getByRole('button',{name:'Open run'}).click();await page.getByRole('heading',{name:'Your confirmed plan'}).waitFor();
  await page.getByRole('button',{name:'Evaluation lab'}).click();
  await page.getByRole('button',{name:'rules',exact:false}).last().waitFor();
  assert.equal(await page.locator('tbody tr').count(),8);
  await page.locator('.experiment').filter({hasText:/^rules/}).click();
  await page.getByRole('heading',{name:'Inspect: rules'}).waitFor();
  await page.getByLabel('Transcript case',{exact:true}).selectOption('test-30');
  assert.ok((await page.locator('.case-panel .saved-transcript').textContent()).includes('Daria'));
  await page.screenshot({path:path.join(screenshotDir,'desktop-benchmarks.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile benchmark overflows viewport');
  await page.screenshot({path:path.join(screenshotDir,'mobile-benchmarks.png'),fullPage:true});
  await page.getByRole('button',{name:'Extract & review'}).click();
  await page.getByLabel('Meeting transcript',{exact:true}).fill('We already reviewed the report.');
  await page.getByRole('button',{name:'Analyze transcript'}).click();
  await page.getByRole('button',{name:'Confirm empty plan'}).waitFor();
  await page.getByRole('button',{name:'Confirm empty plan'}).click();
  await page.getByText('You confirmed a plan with no tasks. All proposals were rejected.',{exact:true}).waitFor();
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile extraction overflows viewport');
  await page.screenshot({path:path.join(screenshotDir,'mobile-confirmed.png'),fullPage:true});
  await page.getByRole('button',{name:'Run history'}).click();
  await page.waitForFunction(()=>document.querySelectorAll('.history-card').length===2);
  assert.deepEqual(errors,[]);
  console.log('Browser smoke passed: dedup, review validation, corrections, confirmation, CSV/JSON, reload, history, benchmark cases, empty plans, mobile layout.');
  console.log(`Screenshots: ${screenshotDir}`);
} catch(error) {
  console.error(error);
  if(browser) await browser.contexts()[0]?.pages()[0]?.screenshot({path:path.join(screenshotDir,'failure.png'),fullPage:true}).catch(()=>{});
  throw error;
} finally {
  await browser?.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));await rm(folder,{recursive:true,force:true});
}
